// Several ISO countries share the same dial code (US/CA both +1, AU/CX/CC
// both +61, GB/GG/IM/JE all +44-ish) so a dial-code string alone can't pick
// a unique option out of the list above. Callers that need a default should
// resolve to an ISO code and look the dial code up from that ISO instead.
export const getDialCodeByIso = (iso) =>
  countryCodes.find((c) => c.iso === iso)?.code || "+91";
